async function main() {
  console.log('🚀 Starting Turbo Air Evaporator import...');

  // Get the evaporation-units category
  const evaporationUnitsCategory = await prisma.category.findUnique({
    where: { slug: 'evaporation-units' },
  });

  if (!evaporationUnitsCategory) {
    console.error('❌ Evaporation Units category not found. Please run seed first.');
    process.exit(1);
  }

  // Delete existing products in evaporation-units category
  console.log('🗑️  Deleting existing evaporation unit products...');
  const deleteResult = await prisma.product.deleteMany({
    where: { categoryId: evaporationUnitsCategory.id },
  });
  console.log(`✅ Deleted ${deleteResult.count} existing products`);

  // Add Turbo Air products
  console.log('📦 Adding Turbo Air evaporator products...');
  let addedCount = 0;

  for (const product of turboAirProducts) {
    await prisma.product.create({
      data: {
        ...product,
        categoryId: evaporationUnitsCategory.id,
      },
    });
    addedCount++;
    console.log(`   ✓ Added: ${product.title}`);
  }

  console.log(`\n✅ Successfully added ${addedCount} Turbo Air products`);
  console.log('\n🎉 Import completed!');
}

main()
  .catch((e) => {
    console.error('❌ Error during import:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
